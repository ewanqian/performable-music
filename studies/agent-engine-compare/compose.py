PARAMS={'title':'Afterimage / two futures','bpm':108,'bars':16,'beats_per_bar':4,'sample_rate':48000,'tail_seconds':3,'preroll_seconds':.05,'voice_amp':.115,'master_ceiling':.75,'piano_brightness':.72,'piano_release_seconds':.24,'memory_brightness':.28,'memory_attack_seconds':.024,'memory_release_seconds':.55,'humanization':'explicit phrase articulation; no random onset jitter','external_plugins':[],'external_samples':[]}
MOTIF={'midi':[69,72,76,77,76,74],'notes':['A4','C5','E5','F5','E5','D5'],'onsets_beats':[0,1.5,2.5,4,5.75,6.5],'durations_beats':[.7,.4,.7,1.2,.45,1.1],'velocities':[73,64,68,80,60,67]}
scores={'A':[],'B':[]}
def note(v,t,p,d,vel=60,role='melody',memory=0):
 scores[v].append({'beat':t,'midi':p,'duration':d,'velocity':vel,'pan':(-.10 if role=='harmony' else (.13 if memory else .04)),'memory':memory,'role':role})
def phrase(v,start,pitches,onsets=None,durs=None,vels=None):
 onsets=MOTIF['onsets_beats'] if onsets is None else onsets
 durs=MOTIF['durations_beats'] if durs is None else durs
 vels=MOTIF['velocities'] if vels is None else vels
 for p,t,d,vel in zip(pitches,onsets,durs,vels):note(v,start+t,p,d,vel)
def chord(v,t,pitches,d=5.6,velocity=45):
 for i,p in enumerate(pitches):note(v,t+i*.018,p,d,velocity+[0,-5,-3,-6][i%4],'harmony')
# Identical two-bar opening establishes both the object of comparison and D as root.
for v in scores:
 phrase(v,0,MOTIF['midi'])
 chord(v,0,[50,57,64],5.6,45)
# A: statement, sequence, contrasting answer, changed return. Harmonic motion has destinations.
phrase('A',8,[77,76,74,72,69],[0,1.5,2.5,4.5,6],[1.1,.5,.85,.7,1.5],[77,66,70,62,68])
