# B: static tonal field, changing expectation. Memory is an explicit earlier-note re-voicing.
phrase('B',8,[69,72,76,77],[.5,2,3,4.5],[.45,.35,.65,1.0],[69,62,65,76])
chord('B',8,[50,57],4.9,39)
phrase('B',16,[76,77,76,77],[.75,1.5,4.25,5.5],[.35,.85,.4,1.1],[65,75,58,67])
note('B',16,50,5.2,38,'harmony')
