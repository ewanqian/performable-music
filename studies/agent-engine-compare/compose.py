note('B',26.25,76,.35,43,'memory',1)
# Bar 8 is genuinely silent: no late-memory onset, sustained note, or effect tail crosses into it.
phrase('B',32,[57,60,64,65],[.75,2.25,3.25,4.75],[.35,.4,.6,1.0],[67,59,63,73])
chord('B',32,[50,57],5.4,37)
phrase('B',40,[76,77],[.5,2.0],[.6,.7],[61,70])
note('B',41.5,72,.3,42,'memory',1)
# Bar 12 is also silent. The listener must supply the missing continuation.
