import assert from 'node:assert/strict';
import { validateContract, makeTrialMatrix, compileCueTimeline, makeMidiSkeleton, inspectVJBake } from '../core.mjs';
import fs from 'node:fs';
const plan=JSON.parse(fs.readFileSync(new URL('../example/critical-field-study.json',import.meta.url),'utf8'));
assert.deepEqual(validateContract(plan).errors,[]);
const trials=makeTrialMatrix(plan);
assert.equal(trials.length,4);
assert.equal(trials.filter(t=>t.changed==='none').length,1);
const timeline=compileCueTimeline(plan);
assert.equal(timeline.cues.length,5);
assert.equal(timeline.cues[3].show_score_event.event.type,'OVERRIDE');
assert.equal(timeline.cues[3].show_score_event.event.source,'foot');
assert.equal(timeline.cues[2].show_score_event.clock.bpm,100);
const midi=makeMidiSkeleton(plan);
assert.equal(midi.toString('ascii',0,4),'MThd');
assert.equal(midi.toString('ascii',14,18),'MTrk');
assert.ok(midi.length>100);
const malformed=structuredClone(plan); malformed.performance.cues[2].t_ms=999999;
assert.equal(validateContract(malformed).ok,false);
const untrusted=structuredClone(plan);untrusted.performance.cues[3].controls.master_gain=100;
assert.equal(validateContract(untrusted).ok,false);
const bypass=structuredClone(plan);bypass.evaluation.human_audio='KEEP';
assert.equal(validateContract(bypass).ok,false);
const v=inspectVJBake({format:'vjbake-1',fps:60,frames:600,duration_sec:10,tempo:{bpm:100}});
assert.equal(v.ok,true);
assert.equal(v.measured_bpm,false);
assert.equal(inspectVJBake({format:'vjbake-1',fps:60,frames:600,duration_sec:99,tempo:{bpm:100}}).ok,false);
console.log('PASS: contract, one-factor trials, v2 Show Score, MIDI bytes, rejection guards, vjbake metadata');
